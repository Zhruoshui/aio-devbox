//! 配方 → fragment 生成器(10-20 design:render.rs 是 recipe-owned fragment
//! 的唯一写入路径)。
//!
//! 三条硬规则由构造保证:
//!   1. 安装位——单二进制 /usr/local/bin/<bin>,tarball /opt/<id>/ + 软链;
//!   2. 不写 /root——模板里根本不出现该路径,产物再过 mod.rs 的 validate()
//!      守卫做纵深防御(自定义片段类型尤其需要);
//!   3. 双通道自检——bash -lc / bash -c 各探一次 command -v(raw 类型除外,
//!      片段作者自理)。
//!
//! 确定性是 AC6 的根基:输出只是 (name, install) 的纯函数,元数据字段
//! (description/category/version/homepage)不进模板,改它们不改变字节。

use super::recipe::{Install, Recipe, UrlKind};

/// Render `recipe` into its `usertools/<id>/fragment.Dockerfile` body. Errors
/// are user-facing (zh); the output always passes `validate` + well-formed
/// markers or the function fails.
pub fn render(id: &str, recipe: &Recipe) -> Result<String, String> {
    super::recipe::validate(recipe, id)?;
    let body = install_body(id, recipe)?;
    let out = format!(
        "# --- tool: {name} ---\n# install: {label}\n{body}# --- /tool ---\n",
        name = recipe.name,
        label = install_label(&recipe.install),
    );
    // Defense in depth: the root-write guard over the GENERATED bytes (the
    // raw type embeds user Dockerfile verbatim; the guard is its only check).
    super::validate(&out)?;
    super::blocks_well_formed(&out)?;
    Ok(out)
}

/// The human-readable install label on the fragment's comment line.
fn install_label(install: &Install) -> String {
    match install {
        Install::Apt { .. } => "apt".into(),
        Install::Url { kind, .. } | Install::GithubRelease { kind, .. } => match kind {
            UrlKind::Binary => "url-binary".into(),
            UrlKind::Tarball => "url-tarball".into(),
        },
        Install::Script { .. } => "script".into(),
        Install::Raw { .. } => "raw".into(),
    }
}

fn install_body(id: &str, recipe: &Recipe) -> Result<String, String> {
    match &recipe.install {
        Install::Apt { packages } => Ok(apt_body(packages)),
        Install::Url { url, kind, bins } => url_body(id, url, *kind, bins),
        Install::GithubRelease { kind, bins, .. } => {
            let url = recipe.install.resolved_url().expect("github-release always resolves");
            url_body(id, &url, *kind, bins)
        }
        Install::Script { script, .. } => Ok(script_body(id, script, recipe)),
        Install::Raw { dockerfile } => Ok(raw_body(dockerfile)),
    }
}

/// Dual-channel self-check tail shared by every generated body EXCEPT raw.
/// `bash -lc` is the WebUI terminal panel (login shell); `bash -c` is
/// code-server's default (non-login) — the two channels the fragment header
/// has always documented.
fn check_tail(check: &str) -> String {
    format!(
        " && bash -lc 'command -v {c} >/dev/null || {{ echo \"MISSING(login): {c}\" >&2; exit 1; }}' \\\n \
         && bash -c  'command -v {c} >/dev/null || {{ echo \"MISSING(non-login): {c}\" >&2; exit 1; }}'\n",
        c = check
    )
}

fn apt_body(packages: &[String]) -> String {
    let mut body = String::from("RUN apt-get update \\\n");
    body.push_str(&format!(
        " && apt-get install -y --no-install-recommends {} \\\n",
        packages.join(" ")
    ));
    body.push_str(" && rm -rf /var/lib/apt/lists/* \\\n");
    body.push_str(&check_tail(packages
        .first()
        .expect("validated non-empty")));
    body
}

fn url_body(id: &str, url: &str, kind: UrlKind, bins: &[String]) -> Result<String, String> {
    let mut body = String::new();
    match kind {
        UrlKind::Binary => {
            let bin = bins.first().cloned().unwrap_or_else(|| id.to_string());
            body.push_str(&format!("RUN curl -fsSL \"{url}\" -o /usr/local/bin/{bin} \\\n"));
            body.push_str(&format!(" && chmod 0755 /usr/local/bin/{bin} \\\n"));
            body.push_str(&check_tail(&bin));
        }
        UrlKind::Tarball => {
            body.push_str(&format!("RUN mkdir -p /opt/{id} \\\n"));
            body.push_str(&format!(" && curl -fsSL \"{url}\" | tar -xz -C /opt/{id} \\\n"));
            for b in bins {
                let base = b.rsplit('/').next().unwrap_or(b);
                body.push_str(&format!(" && ln -sf /opt/{id}/{b} /usr/local/bin/{base} \\\n"));
            }
            let first = bins
                .first()
                .map(|b| b.rsplit('/').next().unwrap_or(b))
                .expect("validated non-empty");
            body.push_str(&check_tail(first));
        }
    }
    Ok(body)
}

fn script_body(id: &str, script: &str, recipe: &Recipe) -> String {
    let mut body = String::from("RUN set -eux; \\\n");
    let lines: Vec<&str> = script.lines().map(str::trim).filter(|l| !l.is_empty()).collect();
    for (i, line) in lines.iter().enumerate() {
        if i + 1 < lines.len() {
            body.push_str(&format!("    {line}; \\\n"));
        } else {
            body.push_str(&format!("    {line} \\\n"));
        }
    }
    let check = recipe
        .install
        .check_cmd(id)
        .unwrap_or_else(|| id.to_string());
    body.push_str(&check_tail(&check));
    body
}

fn raw_body(dockerfile: &str) -> String {
    format!("{dockerfile}\n")
}

#[cfg(test)]
mod tests {
    use super::super::recipe::{Recipe, SCHEMA_VERSION};
    use super::*;

    fn recipe(name: &str, install: Install) -> Recipe {
        Recipe {
            schema: SCHEMA_VERSION,
            name: name.into(),
            description: "d".into(),
            category: "shell".into(),
            version: "v".into(),
            homepage: "https://h".into(),
            install,
        }
    }

    #[test]
    fn apt_body_shape_and_dual_channel() {
        let out = render(
            "htop",
            &recipe("htop", Install::Apt { packages: vec!["htop".into()] }),
        )
        .unwrap();
        assert!(out.starts_with("# --- tool: htop ---\n# install: apt\n"), "{out}");
        assert!(out.contains("--no-install-recommends htop"));
        assert!(out.contains("rm -rf /var/lib/apt/lists/*"));
        assert!(out.contains("bash -lc 'command -v htop"));
        assert!(out.contains("bash -c  'command -v htop"));
        assert!(out.ends_with("# --- /tool ---\n"));
        super::super::validate(&out).unwrap();
    }

    #[test]
    fn metadata_only_edit_leaves_bytes_identical() {
        // AC6 anchor: description/category/version/homepage are render-invisible.
        let base = recipe("htop", Install::Apt { packages: vec!["htop".into()] });
        let a = render("htop", &base).unwrap();
        let mut edited = base.clone();
        edited.description = "完全不同的描述".into();
        edited.category = "document".into();
        edited.version = "9.9".into();
        edited.homepage = "https://elsewhere".into();
        let b = render("htop", &edited).unwrap();
        assert_eq!(a, b);
        // The name is NOT render-invisible (marker payload) — renaming is a
        // visible, hash-changing edit.
        let mut renamed = base.clone();
        renamed.name = "htop-plus".into();
        let c = render("htop", &renamed).unwrap();
        assert_ne!(a, c);
    }

    #[test]
    fn render_is_deterministic() {
        let r = recipe(
            "fd",
            Install::GithubRelease {
                repo: "sharkdp/fd".into(),
                tag: "v10.2.0".into(),
                asset: "fd-v10.2.0-x86_64.tar.gz".into(),
                kind: UrlKind::Tarball,
                bins: vec!["fd-v10.2.0-x86_64/fd".into()],
            },
        );
        assert_eq!(render("fd", &r).unwrap(), render("fd", &r).unwrap());
    }

    #[test]
    fn github_release_url_and_symlinks() {
        let out = render(
            "fd",
            &recipe(
                "fd",
                Install::GithubRelease {
                    repo: "sharkdp/fd".into(),
                    tag: "latest".into(),
                    asset: "fd.tar.gz".into(),
                    kind: UrlKind::Tarball,
                    bins: vec!["fd-v10/fd".into(), "extra/fd-find".into()],
                },
            ),
        )
        .unwrap();
        assert!(out.contains("https://github.com/sharkdp/fd/releases/latest/download/fd.tar.gz"));
        assert!(out.contains("ln -sf /opt/fd/fd-v10/fd /usr/local/bin/fd"));
        assert!(out.contains("ln -sf /opt/fd/extra/fd-find /usr/local/bin/fd-find"));
        assert!(out.contains("command -v fd"));
    }

    #[test]
    fn url_binary_defaults_to_id_name() {
        let out = render(
            "scc",
            &recipe(
                "scc",
                Install::Url { url: "https://e/scc".into(), kind: UrlKind::Binary, bins: vec![] },
            ),
        )
        .unwrap();
        assert!(out.contains("-o /usr/local/bin/scc"));
        assert!(out.contains("chmod 0755 /usr/local/bin/scc"));
    }

    #[test]
    fn script_joins_lines_and_checks() {
        let out = render(
            "mytool",
            &recipe(
                "mytool",
                Install::Script {
                    script: "make build\nmake install PREFIX=/opt/mytool".into(),
                    check: Some("mytool".into()),
                },
            ),
        )
        .unwrap();
        assert!(out.contains("RUN set -eux; \\\n    make build; \\\n    make install PREFIX=/opt/mytool \\\n"));
        assert!(out.contains("command -v mytool"));
    }

    #[test]
    fn raw_is_verbatim_and_still_guarded() {
        let ok = render(
            "weird",
            &recipe("weird", Install::Raw { dockerfile: "RUN install -m 0755 x /usr/local/bin/x".into() }),
        )
        .unwrap();
        assert!(ok.contains("RUN install -m 0755 x /usr/local/bin/x"));

        // The root guard runs over the GENERATED bytes — a raw recipe writing
        // /root fails at render time, not at docker build time.
        let err = render(
            "bad",
            &recipe("bad", Install::Raw { dockerfile: "RUN mkdir -p /root/bin".into() }),
        )
        .unwrap_err();
        assert!(err.contains("/root"), "{err}");
    }

    #[test]
    fn render_rejects_invalid_recipe_fields() {
        let err = render(
            "x",
            &recipe("x", Install::Apt { packages: vec![] }),
        )
        .unwrap_err();
        assert!(err.contains("包名"));
    }
}
